import * as THREE from 'three';

/* ------------------------------------------------------------------
   Twelve stars, twelve records, twelve ways for the tree to look.

   Each theme is a complete palette for the whole scene: what the
   foliage becomes, what the fairy lights burn, what the glass and
   metal ornaments turn into, the ribbons, the sky behind it all.
   `amount` is how far the foliage is pushed away from evergreen —
   the house palette sits at 0 and keeps its own colours.
   ------------------------------------------------------------------ */

const c = (hex) => new THREE.Color(hex);

function theme(o) {
  return {
    amount: 0.88,
    ...o,
    deep: c(o.deep),
    mid: c(o.mid),
    light1: c(o.light1),
    light2: c(o.light2),
    metal: c(o.metal),
    glass: c(o.glass),
    ribbonA: c(o.ribbonA),
    ribbonB: c(o.ribbonB),
    paper: c(o.paper),
    ring: c(o.ring),
    galaxyA: c(o.galaxyA),
    galaxyB: c(o.galaxyB),
    skyHorizon: c(o.skyHorizon),
    skyMid: c(o.skyMid),
    skyTop: c(o.skyTop),
    starCol: c(o.starCol),
    fog: c(o.fog),
  };
}

